"""Node identifier registry.

Two distinct namespaces:

``NodeId``
    Stable identifiers for the future production evaluation nodes described in
    sections 8-23 of the architecture. Declared now so that no node name is ever
    a free-form string duplicated across modules. Almost none of these execute
    in Phase 1A.

``Phase1ANode``
    The infrastructure nodes of the Phase 1A test graph. These are deliberately
    a separate enum so nobody mistakes the infrastructure harness for the real
    evaluation workflow.
"""

from __future__ import annotations

from enum import StrEnum


class NodeId(StrEnum):
    """Production evaluation nodes (architecture sections 8-23).

    Phase 1A declares these identifiers only. Implementations arrive in later
    phases.
    """

    # Intake and understanding (N00-N04)
    INTAKE_GUARD = "INTAKE_GUARD"
    PROJECT_EXTRACTOR = "PROJECT_EXTRACTOR"
    # Phase 1B splits N01 into propose / verify / merge so the trust boundary is
    # a visible node rather than a hidden step inside the extractor.
    PROJECT_EXTRACTOR_VERIFIER = "PROJECT_EXTRACTOR_VERIFIER"
    PROJECT_STATE_MERGE = "PROJECT_STATE_MERGE"
    PROJECT_TYPE_CLASSIFIER = "PROJECT_TYPE_CLASSIFIER"
    CLASSIFICATION_MERGE = "CLASSIFICATION_MERGE"
    OFFICIAL_REQUIREMENTS_CHECK = "OFFICIAL_REQUIREMENTS_CHECK"
    # Phase 2A splits N03 into retrieve / verify / extract so the source
    # verification boundary is a visible node. OFFICIAL_REQUIREMENTS_CHECK names
    # the branch as a whole.
    OFFICIAL_REQUIREMENTS_RETRIEVAL = "OFFICIAL_REQUIREMENTS_RETRIEVAL"
    VERIFY_OFFICIAL_SOURCES = "VERIFY_OFFICIAL_SOURCES"
    EXTRACT_OFFICIAL_REQUIREMENTS = "EXTRACT_OFFICIAL_REQUIREMENTS"
    PROBLEM_VALIDATION = "PROBLEM_VALIDATION"

    # Research planning and parallel branches (N05, N06A-N06D)
    LOAD_PROJECT_STATE = "LOAD_PROJECT_STATE"
    VALIDATE_RESEARCH_INPUT = "VALIDATE_RESEARCH_INPUT"
    RESEARCH_QUERY_PLANNER = "RESEARCH_QUERY_PLANNER"
    VERIFY_QUERY_PLAN = "VERIFY_QUERY_PLAN"
    UPDATE_RESEARCH_COVERAGE = "UPDATE_RESEARCH_COVERAGE"
    ACADEMIC_RESEARCH = "ACADEMIC_RESEARCH"
    # Phase 2B splits N06A into its stages so every trust boundary in academic
    # retrieval -- eligibility, budget, dispatch, normalization, verification,
    # identity resolution -- is a visible node rather than a hidden step.
    # ACADEMIC_RESEARCH names the branch as a whole.
    LOAD_VERIFIED_QUERY_PLAN = "LOAD_VERIFIED_QUERY_PLAN"
    SELECT_ACADEMIC_QUERIES = "SELECT_ACADEMIC_QUERIES"
    ENFORCE_ACADEMIC_BUDGET = "ENFORCE_ACADEMIC_BUDGET"
    DISPATCH_ACADEMIC_PROVIDERS = "DISPATCH_ACADEMIC_PROVIDERS"
    NORMALIZE_ACADEMIC_RESULTS = "NORMALIZE_ACADEMIC_RESULTS"
    VERIFY_ACADEMIC_CANDIDATES = "VERIFY_ACADEMIC_CANDIDATES"
    DEDUPLICATE_ACADEMIC_SOURCES = "DEDUPLICATE_ACADEMIC_SOURCES"
    MERGE_PROVIDER_OBSERVATIONS = "MERGE_PROVIDER_OBSERVATIONS"
    UPDATE_ACADEMIC_COVERAGE = "UPDATE_ACADEMIC_COVERAGE"
    # Phase 2C splits evidence extraction into its stages so the content
    # boundary, the LLM proposal and the deterministic provenance check are each
    # a visible node. CLAIM_EVIDENCE below remains a LATER phase: nothing here
    # decides whether a claim is supported.
    LOAD_RESEARCH_RUN = "LOAD_RESEARCH_RUN"
    VALIDATE_EVIDENCE_INPUT = "VALIDATE_EVIDENCE_INPUT"
    BUILD_CONTENT_SNAPSHOTS = "BUILD_CONTENT_SNAPSHOTS"
    SELECT_EXTRACTABLE_CONTENT = "SELECT_EXTRACTABLE_CONTENT"
    CHUNK_CONTENT_IF_NEEDED = "CHUNK_CONTENT_IF_NEEDED"
    EXTRACT_EVIDENCE_CANDIDATES = "EXTRACT_EVIDENCE_CANDIDATES"
    VERIFY_EVIDENCE_PROVENANCE = "VERIFY_EVIDENCE_PROVENANCE"
    VERIFY_NUMERIC_FIDELITY = "VERIFY_NUMERIC_FIDELITY"
    DEDUPLICATE_EVIDENCE = "DEDUPLICATE_EVIDENCE"
    UPDATE_EVIDENCE_COVERAGE = "UPDATE_EVIDENCE_COVERAGE"
    FINALIZE_EVIDENCE_EXTRACTION = "FINALIZE_EVIDENCE_EXTRACTION"
    # Phase 2D adds the claim-evidence alignment branch. It consumes existing
    # claims and accepted Phase 2C evidence and produces a semantic relation
    # record; the nominal CLAIM_EVIDENCE node above remains the later,
    # fuller claim-evidence engine described in the architecture (section 17).
    LOAD_ALIGNMENT_RUN = "LOAD_ALIGNMENT_RUN"
    VALIDATE_ALIGNMENT_INPUT = "VALIDATE_ALIGNMENT_INPUT"
    GENERATE_ALIGNMENT_PAIRS = "GENERATE_ALIGNMENT_PAIRS"
    CLASSIFY_ALIGNMENT_CANDIDATES = "CLASSIFY_ALIGNMENT_CANDIDATES"
    VERIFY_ALIGNMENT_CANDIDATES = "VERIFY_ALIGNMENT_CANDIDATES"
    UPDATE_ALIGNMENT_COVERAGE = "UPDATE_ALIGNMENT_COVERAGE"
    FINALIZE_CLAIM_EVIDENCE_ALIGNMENT = "FINALIZE_CLAIM_EVIDENCE_ALIGNMENT"

    # Phase 2E adds the claim-sufficiency branch over Phase 2D alignments. It
    # computes an auditable evidence posture per claim and mutates no claim,
    # score or trust verdict; SCORING and TRUST_GATE below stay later phases.
    LOAD_SUFFICIENCY_RUN = "LOAD_SUFFICIENCY_RUN"
    VALIDATE_SUFFICIENCY_INPUT = "VALIDATE_SUFFICIENCY_INPUT"
    BUILD_INDEPENDENCE_GROUPS = "BUILD_INDEPENDENCE_GROUPS"
    BUILD_EVIDENCE_WEIGHT_PROFILES = "BUILD_EVIDENCE_WEIGHT_PROFILES"
    BUILD_CLAIM_COMPONENT_INVENTORY = "BUILD_CLAIM_COMPONENT_INVENTORY"
    AGGREGATE_CLAIM_COMPONENT_COVERAGE = "AGGREGATE_CLAIM_COMPONENT_COVERAGE"
    APPLY_SUFFICIENCY_POLICY = "APPLY_SUFFICIENCY_POLICY"
    FINALIZE_CLAIM_SUFFICIENCY = "FINALIZE_CLAIM_SUFFICIENCY"

    # Phase 2F adds the claim-evidence scoring branch over Phase 2E. It derives
    # a deterministic, policy-versioned evidence index per claim and writes no
    # project score: SCORING below remains a later project-evaluation phase,
    # and an evidence index is not a rubric score (ADR-017).
    LOAD_SCORING_RUN = "LOAD_SCORING_RUN"
    VALIDATE_SCORING_INPUT = "VALIDATE_SCORING_INPUT"
    DERIVE_COMPONENT_SCORE_TRACES = "DERIVE_COMPONENT_SCORE_TRACES"
    CALCULATE_SUPPORT_CHANNEL = "CALCULATE_SUPPORT_CHANNEL"
    CALCULATE_CONTRADICTION_CHANNEL = "CALCULATE_CONTRADICTION_CHANNEL"
    DERIVE_SCORE_RELIABILITY = "DERIVE_SCORE_RELIABILITY"
    APPLY_SCORE_DISPOSITION_POLICY = "APPLY_SCORE_DISPOSITION_POLICY"
    BUILD_CLAIM_EVIDENCE_SCORECARDS = "BUILD_CLAIM_EVIDENCE_SCORECARDS"
    FINALIZE_CLAIM_EVIDENCE_SCORING = "FINALIZE_CLAIM_EVIDENCE_SCORING"

    # Phase 2G implements the PATENT research branch as its own node sequence:
    # bounded patent search, bibliographic verification, family grouping,
    # text acquisition and chronology. It produces research candidates for a
    # later comparison phase and never a novelty, patentability or legal
    # prior-art conclusion; NOVELTY and CLOSEST_PRIOR_ART stay later (ADR-018).
    LOAD_PATENT_RESEARCH_RUN = "LOAD_PATENT_RESEARCH_RUN"
    PLAN_PATENT_QUERIES = "PLAN_PATENT_QUERIES"
    EXECUTE_PATENT_SEARCH = "EXECUTE_PATENT_SEARCH"
    VERIFY_PATENT_PUBLICATIONS = "VERIFY_PATENT_PUBLICATIONS"
    RESOLVE_PATENT_FAMILIES = "RESOLVE_PATENT_FAMILIES"
    CAPTURE_PATENT_TEXT = "CAPTURE_PATENT_TEXT"
    BUILD_PATENT_CANDIDATES = "BUILD_PATENT_CANDIDATES"
    FINALIZE_PATENT_RESEARCH = "FINALIZE_PATENT_RESEARCH"
    PATENT_RESEARCH = "PATENT_RESEARCH"

    # Phase 2H implements the PRODUCT and OPEN_SOURCE research tracks: bounded
    # web and repository discovery, SSRF-safe artifact fetching, product
    # identity, repository identity and networks, and chronology. It ends at
    # discovery candidates; NOVELTY and CLOSEST_PRIOR_ART stay later (ADR-019).
    LOAD_PRODUCT_OSS_RESEARCH_RUN = "LOAD_PRODUCT_OSS_RESEARCH_RUN"
    PLAN_PRODUCT_OSS_QUERIES = "PLAN_PRODUCT_OSS_QUERIES"
    EXECUTE_PRODUCT_SEARCH = "EXECUTE_PRODUCT_SEARCH"
    FETCH_PRODUCT_ARTIFACTS = "FETCH_PRODUCT_ARTIFACTS"
    RESOLVE_PRODUCT_IDENTITY = "RESOLVE_PRODUCT_IDENTITY"
    BUILD_PRODUCT_CANDIDATES = "BUILD_PRODUCT_CANDIDATES"
    EXECUTE_OPEN_SOURCE_SEARCH = "EXECUTE_OPEN_SOURCE_SEARCH"
    VERIFY_REPOSITORIES = "VERIFY_REPOSITORIES"
    CAPTURE_REPOSITORY_SNAPSHOTS = "CAPTURE_REPOSITORY_SNAPSHOTS"
    RESOLVE_REPOSITORY_NETWORKS = "RESOLVE_REPOSITORY_NETWORKS"
    BUILD_OPEN_SOURCE_CANDIDATES = "BUILD_OPEN_SOURCE_CANDIDATES"
    FINALIZE_PRODUCT_OSS_RESEARCH = "FINALIZE_PRODUCT_OSS_RESEARCH"
    PRODUCT_RESEARCH = "PRODUCT_RESEARCH"
    OPEN_SOURCE_RESEARCH = "OPEN_SOURCE_RESEARCH"

    # Phase 2I compares existing claims against the Phase 2G/2H candidates and
    # synthesizes a DESCRIPTIVE technical overlap / differentiation posture in
    # Python. It is deliberately not the NOVELTY node: there is no legal
    # novelty verdict, no patentability and no score anywhere in it (ADR-020).
    LOAD_NOVELTY_DIFFERENTIATION_RUN = "LOAD_NOVELTY_DIFFERENTIATION_RUN"
    BUILD_COMPARISON_FEATURE_INVENTORY = "BUILD_COMPARISON_FEATURE_INVENTORY"
    PROFILE_PRIOR_ART_CANDIDATES = "PROFILE_PRIOR_ART_CANDIDATES"
    COMPARE_CLAIM_CANDIDATES = "COMPARE_CLAIM_CANDIDATES"
    SYNTHESIZE_CLAIM_DIFFERENTIATION = "SYNTHESIZE_CLAIM_DIFFERENTIATION"
    SYNTHESIZE_PROJECT_DIFFERENTIATION = "SYNTHESIZE_PROJECT_DIFFERENTIATION"
    FINALIZE_NOVELTY_DIFFERENTIATION = "FINALIZE_NOVELTY_DIFFERENTIATION"

    # Phase 2J assesses whether the bounded evidence supports a research /
    # engineering gap the project targets. It is deliberately not the GAP node
    # (which would write ProjectState.gap): an evidence-bounded posture, never a
    # methodology, result or score judgment (ADR-021).
    LOAD_GAP_ASSESSMENT_RUN = "LOAD_GAP_ASSESSMENT_RUN"
    BUILD_GAP_EVIDENCE_INVENTORY = "BUILD_GAP_EVIDENCE_INVENTORY"
    EXTRACT_GAP_CANDIDATES = "EXTRACT_GAP_CANDIDATES"
    VERIFY_GAP_PROJECT_LINKAGE = "VERIFY_GAP_PROJECT_LINKAGE"
    REVIEW_GAP_COUNTEREVIDENCE = "REVIEW_GAP_COUNTEREVIDENCE"
    SYNTHESIZE_CLAIM_GAPS = "SYNTHESIZE_CLAIM_GAPS"
    SYNTHESIZE_PROJECT_GAPS = "SYNTHESIZE_PROJECT_GAPS"
    FINALIZE_GAP_ASSESSMENT = "FINALIZE_GAP_ASSESSMENT"

    # Phase 3A reviews the DESIGN of the documented methodology. It is deliberately
    # not the METHODOLOGY node below (which would write ProjectState.methodology):
    # a design-level posture, never an execution, result or score judgment (ADR-022).
    LOAD_METHODOLOGY_REVIEW_RUN = "LOAD_METHODOLOGY_REVIEW_RUN"
    BUILD_METHODOLOGY_REQUIREMENT_INVENTORY = "BUILD_METHODOLOGY_REQUIREMENT_INVENTORY"
    RESOLVE_METHODOLOGY_OVERLAYS = "RESOLVE_METHODOLOGY_OVERLAYS"
    EXTRACT_METHODOLOGY_EVIDENCE = "EXTRACT_METHODOLOGY_EVIDENCE"
    RESOLVE_METHODOLOGY_APPLICABILITY = "RESOLVE_METHODOLOGY_APPLICABILITY"
    ASSESS_METHODOLOGY_COMPONENTS = "ASSESS_METHODOLOGY_COMPONENTS"
    LINK_METHODOLOGY_TO_TARGETS = "LINK_METHODOLOGY_TO_TARGETS"
    EVALUATE_VALIDATION_CONTINUITY = "EVALUATE_VALIDATION_CONTINUITY"
    SYNTHESIZE_METHODOLOGY_POSTURE = "SYNTHESIZE_METHODOLOGY_POSTURE"
    FINALIZE_METHODOLOGY_REVIEW = "FINALIZE_METHODOLOGY_REVIEW"

    # Phase 3B reviews each documented experiment PROTOCOL. It is deliberately not
    # the EXPERIMENT_REVIEW node below: a protocol-level posture, never an execution,
    # result or score judgment (ADR-023). Values equal ``ExperimentStage``.
    EXPERIMENT_BIND_INPUTS = "EXPERIMENT_BIND_INPUTS"
    EXPERIMENT_SEGMENT = "EXPERIMENT_SEGMENT"
    EXPERIMENT_EXTRACT_PROTOCOL = "EXPERIMENT_EXTRACT_PROTOCOL"
    EXPERIMENT_RESOLVE_APPLICABILITY = "EXPERIMENT_RESOLVE_APPLICABILITY"
    EXPERIMENT_LINK_TARGETS = "EXPERIMENT_LINK_TARGETS"
    EXPERIMENT_SYNTHESIZE = "EXPERIMENT_SYNTHESIZE"
    EXPERIMENT_FINALIZE = "EXPERIMENT_FINALIZE"

    # Source handling (N07, N08)
    SOURCE_NORMALIZATION = "SOURCE_NORMALIZATION"
    SOURCE_QUALITY = "SOURCE_QUALITY"

    # Analysis (N09-N15)
    CLOSEST_PRIOR_ART = "CLOSEST_PRIOR_ART"
    NOVELTY = "NOVELTY"
    GAP = "GAP"
    METHODOLOGY = "METHODOLOGY"
    EXPERIMENT_REVIEW = "EXPERIMENT_REVIEW"
    CLAIM_EVIDENCE = "CLAIM_EVIDENCE"
    CONTRADICTION_DETECTION = "CONTRADICTION_DETECTION"

    # Adversarial review and finalization (N16-N20)
    RED_TEAM = "RED_TEAM"
    SCORING = "SCORING"
    TRUST_GATE = "TRUST_GATE"
    FINAL_VERIFIER = "FINAL_VERIFIER"
    REPORT_GENERATOR = "REPORT_GENERATOR"


