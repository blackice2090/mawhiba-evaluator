def cell(kind: str, experiment_type: str) -> str:
    """The catalog cell for a kind and type: R, C, O or -. An UNKNOWN type: R for universal rows, else C."""
    fam = TYPE_FAMILY[experiment_type]
    if fam is None:
        return "R" if kind in UNIVERSAL else "C"
    override = OVERRIDES.get(experiment_type, {}).get(kind)
    return override if override is not None else _ROWS[kind][0][FAMILIES.index(fam)]


def required_kinds(experiment_type: str, fired: dict[str, tuple[str, ...]] | None = None,
                   phase2j: tuple[str, ...] = ()) -> list[str]:
    """Kinds that are REQUIRED once ``fired`` maps conditional kinds to the closed triggers the model found and
    ``phase2j`` lists the Phase 2J triggers that reach the experiment (only via a tested target)."""
    fired = fired or {}
    out = []
    for kind in KINDS:
        c = cell(kind, experiment_type)
        if c == "R":
            out.append(kind)
        elif c == "C":
            own = set(fired.get(kind, ())) & set(TRIGGERS[kind])
            if own or set(TRIGGERS[kind]) & set(phase2j):
                out.append(kind)
    return out


def conditional_kinds(experiment_type: str) -> list[str]:
    return [k for k in KINDS if cell(k, experiment_type) == "C"]


def model_triggers(kind: str) -> tuple[str, ...]:
    return tuple(t for t in TRIGGERS[kind] if t not in PHASE_2J_TRIGGERS)


def missing_issue(kind: str) -> str:
    return MISSING_ISSUE.get(kind, FALLBACK_MISSING_ISSUE)


def is_major(issue: str) -> bool:
    return SEVERITY[issue] in MAJOR_SEVERITIES


def worst(postures: list[str]) -> str:
    return min(postures, key=WORST_ORDER.index)
